// =====================================================
// IMPORT EVENTS
//
// Public entry point.
//
// CSV
//      ↓
// process()
//      ↓
// validateEvent()
//      ↓
// resolveEvent()
//      ↓
// buildCommitPlan()
//      ↓
// commit()
//      ↓
// finish()
//
// =====================================================

export async function importEvents(

    file

) {

    const result =

        await process({

            file,

            validator:

                validateEvent,

            resolver:

                resolveEvent,

            commitPlanBuilder:

                buildCommitPlan

        })

    const preview =

        buildPreview(

            result

        )

    return {

        stage:

            'preview',

        preview,

        approve:

            async () => {

                const context =

                    begin()

                const commitResult =

                    await commit(

                        context,

                        result.commitPlan

                    )

                const finished =

                    finish(

                        commitResult

                    )

                const report = {

                    module:

                        'Events',

                    source:

                        result.raw?.source,

                    startedAt:

                        finished.startedAt,

                    completedAt:

                        finished.completedAt,

                    summary: {

                        totalRows:

                            result.normalized?.totalRows || 0,

                        importedRows:

                            finished.committed || 0,

                        warningRows:

                            result.resolved?.warnings?.length || 0,

                        errorRows:

                            finished.errors?.length || 0

                    },

                    warnings:

                        result.resolved?.warnings || [],

                    errors:

                        [

                            ...(result.resolved?.errors || []),

                            ...(finished.errors || [])

                        ]

                }

                return {

                    ...finished,

                    summary:

                        buildSummary(

                            report

                        ),

                    downloads:

                        await downloadFullPackage(

                            report

                        )

                }

            }

    }

}
// =====================================================
// EVENT VALIDATION
//
// Contains ONLY event business rules.
//
// Uses the generic validation library already
// supplied by importService.
//
// No generic validation code belongs here.
//
// =====================================================

export async function validateEvent(

    importData,

    validation

) {

    const errors = []

    validateRequiredFields(

        importData,

        validation,

        errors

    )

    validateEventDates(

        importData,

        validation,

        errors

    )

    validateDuplicateEvents(

        importData,

        validation,

        errors

    )

    return {

        ...importData,

        valid:

            errors.length === 0,

        errors

    }

}

// =====================================================
// REQUIRED FIELD VALIDATION
// =====================================================

function validateRequiredFields(

    importData,

    validation,

    errors

) {

    for (

        const [

            index,

            row

        ]

        of (

            importData.objects || []

        ).entries()

    ) {

        const requiredFields = [

    [
        'town_name',
        'Town'
    ],

    [
        'event_category_code',
        'Event Category'
    ],

    [
        'event_type_code',
        'Event Type'
    ],

    [
        'event_status_code',
        'Event Status'
    ],

    [
        'start_date',
        'Start Date'
    ],

    [
        'end_date',
        'End Date'
    ]

]

        for (

            const [

                field,

                label

            ]

            of requiredFields

        ) {

            const result =

                validation.validateRequired(

                    row[field],

                    label

                )

            if (

                !result.valid

            ) {

                errors.push({

                    row:

                        index + 1,

                    field,

                    message:

                        result.message

                })

            }

        }

    }

}

// =====================================================
// EVENT DATE VALIDATION
// =====================================================

function validateEventDates(

    importData,

    validation,

    errors

) {

    for (

        const [

            index,

            row

        ]

        of (

            importData.objects || []

        ).entries()

    ) {

        const startDate =

            validation.validateDate(

                row.start_date

            )

        if (

            !startDate.valid

        ) {

            errors.push({

                row:

                    index + 1,

                field:

                    'start_date',

                message:

                    startDate.message

            })

        }

        const endDate =

            validation.validateDate(

                row.end_date

            )

        if (

            !endDate.valid

        ) {

            errors.push({

                row:

                    index + 1,

                field:

                    'end_date',

                message:

                    endDate.message

            })

        }

        if (

            row.start_date &&

            row.end_date &&

            new Date(

                row.end_date

            ) <

            new Date(

                row.start_date

            )

        ) {

            errors.push({

                row:

                    index + 1,

                field:

                    'end_date',

                message:

                    'End Date cannot be earlier than Start Date.'

            })

        }

    }

}

// =====================================================
// DUPLICATE EVENT VALIDATION
// =====================================================

function validateDuplicateEvents(

    importData,

    validation,

    errors

) {

    const duplicates =

        validation.validateDuplicates(

            importData.objects || [],

            [
    'town_name',
    'event_type_code',
    'event_category_code',
    'start_date',
    'start_time'
]
        )

    if (

        !duplicates.valid

    ) {

        errors.push(

            ...(duplicates.value || [])

        )

    }

}

// =====================================================
// LOOKUP VALIDATION
// =====================================================
//
// Placeholder.
//
// This executes AFTER lookup resolution.
//
// It validates:
//
// Town
// Event Type
// Event Category
// Status
// Sponsor
//
// using the resolver results.
//
// =====================================================

function validateLookupFields(

    resolvedData,

    errors

) {

    for (

        const [

            index,

            row

        ]

        of (

            resolvedData.objects || []

        ).entries()

    ) {

        validateLookup(

            index,

            row,

            'town',

            'Town',

            errors

        )

        validateLookup(

            index,

            row,

            'category',

            'Event Category',

            errors

        )

        validateLookup(

            index,

            row,

            'eventType',

            'Event Type',

            errors

        )

        validateLookup(

            index,

            row,

            'status',

            'Status',

            errors

        )

        if (

            row.sponsor

        ) {

            validateLookup(

                index,

                row,

                'sponsor',

                'Sponsor',

                errors

            )

        }

    }

    return errors

}

function validateLookup(

    rowIndex,

    row,

    property,

    label,

    errors

) {

    const lookup =

        row[
            property
        ]

    if (

        lookup?.found

    ) {

        return

    }

    errors.push({

        row:

            rowIndex + 1,

        field:

            property,

        message:

            `${label} was not found.`

    })

}




// =====================================================
// EVENT LOOKUP RESOLUTION
//
// Resolves:
//
// County
// Subcounty
// Town
// Event Category
// Event Type
// Status
// Sponsor
//
// Uses lookupResolver.
//
// No SQL.
//
// =====================================================

export async function resolveEvent(

    validatedData,

    lookup

) {

    const resolvedObjects = []

    for (

        const importObject

        of validatedData.objects || []

    ) {

        const resolvedObject =

            await resolveImportObject(

                importObject,

                lookup

            )

        const generatedObject =

            generateDerivedFields(

                resolvedObject

            )

        resolvedObjects.push(

            buildCommitObject(

                generatedObject

            )

        )

    }

    const resolvedData = {

        ...validatedData,

        objects:

            resolvedObjects

    }

    const errors = [

        ...(validatedData.errors || [])

    ]

    validateLookupFields(

        resolvedData,

        errors

    )

    return {

        ...resolvedData,

        valid:

            errors.length === 0,

        errors

    }

}

// =====================================================
// RESOLVE IMPORT OBJECT
//
// Converts an Import Object into a fully
// Resolved Object.
//
// =====================================================

async function resolveImportObject(

    importObject = {},

    lookup

) {

    const town =

        await lookup.resolveTown(

            importObject.town_name

        )

    const subcounty =

    town.record

        ? await lookup.resolveSubcountyById(

            town.record.subcounty_id

        )

        : {

            found: false,

            id: null,

            record: null

        }

const county =

    subcounty.record

        ? await lookup.resolveCountyById(

            subcounty.record.county_id

        )

        : {

            found: false,

            id: null,

            record: null

        }

const country =

    county.record

        ? await lookup.resolveCountryById(

            county.record.country_id

        )

        : {

            found: false,

            id: null,

            record: null

        }

    const eventType =

    await lookup.resolveEventTypeCode(

        importObject.event_type_code

    )

    const category =

        await lookup.resolveCategoryCode(

    importObject.event_category_code

)

        

    const status =

        await lookup.resolveEventStatusCode(

    importObject.event_status_code

)
        

  const sponsor =

    await lookup.resolveSponsorCode(

        importObject.sponsor_code

    )



    return {

    ...importObject,

    town,

    subcounty,

    county,

    country,

    eventType,

    category,

    status,

    sponsor,

    

}

}
// =====================================================
// GENERATE DERIVED FIELDS
//
// Generates fields that are not supplied by the CSV.
//
// =====================================================

// =====================================================
// GENERATE DERIVED FIELDS
//
// Converts a Resolved Object into a
// Generated Object.
//
// =====================================================

function generateDerivedFields(

    resolvedObject = {}

) {

    return {

    ...resolvedObject,

    [GENERATED_FIELDS.COUNTRY_ID]:

        resolvedObject.country?.id ?? null,

    [GENERATED_FIELDS.EVENT_NAME]:

        [

            resolvedObject.town?.name,

            resolvedObject.eventType?.name

        ]

        .filter(Boolean)

        .join(' '),

    [GENERATED_FIELDS.EVENT_AREA]:

        [

            resolvedObject.town?.name,

            resolvedObject.eventType?.name

        ]

        .filter(Boolean)

        .join(' ')

}

}

