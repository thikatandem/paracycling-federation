// =====================================================
// COLLECT OPERATIONS
//
// =====================================================

function collectOperations(

    resolvedData = {}

) {

    return [

        buildEventMaster(

            resolvedData

        ),

        buildOccurrences(

            resolvedData

        ),

        buildSponsors(

            resolvedData

        )

    ].filter(

        operation =>

            operation.records.length > 0

    )

}


export function buildCommitPlan(

    resolvedData = {}

) {

    return {

        stages: [

            {

                name:

                    'events',

                operations: [

                    buildEventMaster(

                        resolvedData

                    )

                ]

            },

            {

                name:

                    'occurrences',

                dependsOn: [

                    'events'

                ],

                operations: [

                    buildOccurrences(

                        resolvedData

                    )

                ]

            },

            {

                name:

                    'sponsors',

                dependsOn: [

                    'occurrences'

                ],

                operations: [

                    buildSponsors(

                        resolvedData

                    )

                ]

            }

        ]

    }

}

// =====================================================
// UNIQUE EVENTS
//
// Groups duplicate event masters.
//
// =====================================================

function uniqueEvents(

    objects = []

) {

    const events =

        new Map()

    objects.forEach(

        object => {

           const businessKey = [

    object[
       COMMIT_FIELDS.TOWN_ID
    ],

    object[
        COMMIT_FIELDS.EVENT_TYPE_ID
    ],

    object[
        COMMIT_FIELDS.EVENT_CATEGORY_ID
    ]

].join('|')

events.set(

    businessKey,

    {

        event_name:

            object[
                GENERATED_FIELDS.EVENT_NAME
            ],

        event_category_id:

            object[
                COMMIT_FIELDS.EVENT_CATEGORY_ID
            ],

        event_type_id:

            object[
                COMMIT_FIELDS.EVENT_TYPE_ID
            ]

    }

)

        }

    )

    return [

        ...events.values()

    ]

}




