// =====================================================
// BUILD EVENT MASTER
//
// Builds unique records for:
//
// events
//
// =====================================================

function buildEventMaster(

    resolvedData = {}

) {

    const records =

        uniqueEvents(

            resolvedData.objects || []

        )

   return {

    table:

        EVENT_TABLES.EVENTS,

    operation:

    'upsert',

records,

conflictColumn:

    'event_name',

options:

    DEFAULT_OPTIONS,

    identity: {

        collection:

            'events',

        databaseKey:

            'event_id',

       businessKey(

    record

) {

    if (

        record[
            IMPORT_FIELDS.EVENT_ID
        ]

    ) {

        return `ID:${
            record[
                IMPORT_FIELDS.EVENT_ID
            ]
        }`

    }

    if (

        record[
            IMPORT_FIELDS.EVENT_CODE
        ]

    ) {

        return `CODE:${
            record[
                IMPORT_FIELDS.EVENT_CODE
            ]
        }`

    }

    return [

        record[
            COMMIT_FIELDS.TOWN_ID
        ],

        record[
            COMMIT_FIELDS.EVENT_CATEGORY_ID
        ],

        record[
            COMMIT_FIELDS.EVENT_TYPE_ID
        ]

    ].join('|')

}

    }

}

}


